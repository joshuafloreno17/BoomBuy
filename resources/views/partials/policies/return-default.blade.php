            <div class="terms-section">
                <h3>1. Return Window</h3>
                <p>Buyers may request a return or refund for an item within 7 days after confirming that the order was received.</p>
            </div>

            <div class="terms-section">
                <h3>2. How to Request</h3>
                <p>Open My Orders, choose the delivered order, and tap Return / Refund. Pick the item and a reason, describe the problem, attach a clear photo whenever possible, and enter the GCash, Maya or bank account where your refund should go. Choose <strong>Return the item</strong> if you will send it back, or <strong>Refund only</strong> if there is nothing to send (for example, a missing item).</p>
            </div>

            <div class="terms-section">
                <h3>3. Seller Review</h3>
                <p>The seller has 3 days to approve or reject the request. If they don't answer in time, BoomBuy decides it. If the seller rejects it and you disagree, tap <strong>Ask BoomBuy to review</strong> within 7 days — BoomBuy's decision is final.</p>
            </div>

            <div class="terms-section">
                <h3>4. Sending the Item Back</h3>
                <p>Once a return is approved, pack the item and bring it to your BoomBuy Sorting Center within 7 days, telling the staff your return number. It travels back to the seller through the Sorting Centers. Returns not brought in within 7 days are cancelled.</p>
            </div>

            <div class="terms-section">
                <h3>5. Refunds</h3>
                <p>BoomBuy sends the refund to the account you entered: the price you paid for the item, less its share of any voucher discount. The delivery fee is not refunded. For a return, the refund is sent once the seller has the item back; for a refund-only request, once it is approved. You will see the transfer's reference number on your order.</p>
            </div>

            <div class="terms-section">
                <h3>6. Cancellations</h3>
                <p>Cash on Delivery orders may be cancelled by the buyer while they are still Pending or Processing. Orders the seller doesn't confirm within 3 days are cancelled automatically. Frequent cancellations or refused parcels may temporarily pause Cash on Delivery for that account.</p>
            </div>

            <div class="terms-section">
                <h3>7. Need Help?</h3>
                <p>For anything else, file a complaint from Help &amp; Complaints and an administrator will look into it.</p>
            </div>
