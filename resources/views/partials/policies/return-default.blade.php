            <div class="terms-section">
                <h3>1. Return Window</h3>
                <p>Buyers may request a return or refund for an item within 7 days after confirming that the order was received.</p>
            </div>

            <div class="terms-section">
                <h3>2. How to Request</h3>
                <p>Open My Orders, choose the delivered order, and select Return/Refund on the item. Pick a reason, describe the problem, and attach a clear photo as evidence whenever possible.</p>
            </div>

            <div class="terms-section">
                <h3>3. Seller Review</h3>
                <p>The seller reviews each request and may approve or reject it. If a return is approved, the buyer sends the item back and the seller confirms once it arrives.</p>
            </div>

            <div class="terms-section">
                <h3>4. Refunds</h3>
                <p>Approved refunds cover the price of the returned item. The buyer is notified at each step until the seller marks the refund as completed.</p>
            </div>

            <div class="terms-section">
                <h3>5. Cancellations</h3>
                <p>Cash on Delivery orders may be cancelled by the buyer while they are still Pending or Processing. Frequent cancellations or refused parcels may temporarily pause Cash on Delivery for that account.</p>
            </div>

            <div class="terms-section">
                <h3>6. Need Help?</h3>
                <p>If a seller does not respond or you disagree with a decision, file a complaint from Help &amp; Complaints and an administrator will look into it.</p>
            </div>
